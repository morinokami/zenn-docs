import { Link } from "@chibivoid/react";
import type { Props } from "./index.server.ts";

export default function Users({ users }: Props) {
  return (
    <div>
      <h1>Users</h1>
      <ul>
        {users.map((user) => (
          <li key={user.id}>
            <Link href={`/users/${user.id}`}>{user.name}</Link>
          </li>
        ))}
      </ul>
    </div>
  );
}
